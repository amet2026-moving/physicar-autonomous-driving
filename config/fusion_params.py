# 카메라(차선)와 라이다(클러스터) 정보를 합칠 때만 쓰는 상수.
#
# camera_params.py/lidar_params.py 어느 쪽에도 안 넣은 이유: 이 값들은 "카메라
# 픽셀 좌표"와 "라이다 미터 좌표"를 하나의 기준(프레임/차량 중심 대비 비율)으로
# 정규화해서 비교하기 위한 값이라, 두 센서를 동시에 알아야만 의미가 있음.
#
# 카메라<->라이다 외부 캘리브레이션(정확한 물리적 장착 위치/각도 차이)이 이
# 저장소에 없어서, 절대 좌표 변환 대신 "각자 자기 기준에서 중심 대비 얼마나
# 벗어났는지 비율"로 맞춘 뒤 그 비율끼리 비교하는 방식을 쓴다 (AutoV3_fusion.py
# 검증 방식 그대로). FUSION_LATERAL_HALF_WIDTH_M은 실측 없이 넣은 잠정값 --
# ROI_NORM/FIXED_ROI_NORM처럼 실차에서 확인 후 조정할 것.

# 라이다 cy(횡방향, m, +좌/-우)가 이 값에 도달하면 '차량 정면축에서 크게
# 벗어났다'(비율 1.0)고 볼 물리 거리 기준 (m).
FUSION_LATERAL_HALF_WIDTH_M = 0.6

# cy가 이 값보다 작으면(라이다 정면축상 거의 정중앙) 차선 기준선과 비교할 것도 없이
# 곧바로 IN_CORRIDOR로 본다 -- 바로 앞을 막고 있는 게 명백하므로.
FUSION_CY_DEADBAND_M = 0.03

# 코리도 폭(lane_obs.lane_width_px) 좌우로 추가 확보하는 안전 여유 비율. 차선 인식이
# 살짝 흔들려도 코리도 경계 바로 안쪽 장애물을 놓치지 않기 위함.
FUSION_CORRIDOR_MARGIN_RATIO = 0.15

# lane_obs.lane_width_px(코리도 폭 EMA)가 아직 한 번도 추정되지 않았을 때(예: 주행
# 시작 직후) 쓰는 기본 코리도 폭 -- BEV 프레임 폭 대비 비율. 실차 확인 후 재조정할 것.
FUSION_DEFAULT_CORRIDOR_WIDTH_RATIO = 0.30
